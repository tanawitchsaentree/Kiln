#!/usr/bin/env node
// design-md — writes DESIGN.md at the repo root: the system in one file for any AI tool that builds
// UI (Stitch, Cursor, v0, Claude without kiln). It is generated from what the system already holds,
// never written by hand: tokens.json (values per theme and each token's reason), system/CONCEPT.md
// (the principles), every <Name>.why.json (what the component is and the default it must not become)
// and system/DECISIONS.md (the locked rules). A tool reading it has no gates, so the file says which
// measurements kiln would have run and asks the tool to keep to them.
//
// Usage: node tooling/kiln/design-md.mjs [--out DESIGN.md]   (default: DESIGN.md and <docs app>/public/DESIGN.md;
// verify runs it before the book is built)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT, docsConfig } from './config.mjs';

const C = docsConfig();
const SYS = JSON.parse(readFileSync(path.join(ROOT, 'system', 'kiln.config.json'), 'utf8'));
const read = (f) => (existsSync(path.join(ROOT, f)) ? readFileSync(path.join(ROOT, f), 'utf8') : '');
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const OUT = path.resolve(ROOT, arg('--out') ?? 'DESIGN.md');
const pkg = (dir) => { try { return JSON.parse(readFileSync(path.join(ROOT, dir, 'package.json'), 'utf8')).name; } catch { return null; } };
const tokensPkg = pkg('packages/tokens'); const reactPkg = pkg(C.componentsPackage);
const tokens = JSON.parse(read('packages/tokens/build/json/tokens.json') || '{}');
const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const cell = (s) => one(s).replace(/\|/g, '\\|');

// --- concept: the opening paragraph and each principle with its first sentence
const concept = read('system/CONCEPT.md');
const NAME = (SYS.name && !/\{\{/.test(SYS.name) ? SYS.name : null) ?? concept.match(/^# Concept\W+(.+)$/m)?.[1]?.trim() ?? reactPkg?.replace(/-react$/, '') ?? 'design system';
const intro = one(concept.split(/\n## /)[0].replace(/^# .*\n/, ''));
const principles = [...concept.matchAll(/^### (P\d+) (.+)\n([^\n]+)/gm)].map(([, id, title, line]) => ({ id, title, line: one(line) }));

// --- tokens: semantic tier, grouped by the first segment, with the base value and each other theme
const base = SYS.tokens?.baseTheme ?? 'dark';
const sem = Object.entries(tokens).filter(([, t]) => t.tier === 'semantic');
const groups = {};
for (const [p, t] of sem) (groups[p.split('.')[0]] ??= []).push([p, t]);
const themes = [base, ...new Set(sem.flatMap(([, t]) => Object.keys(t.themes ?? {})))];
const val = (t, th) => (th === base ? t.value : t.themes?.[th]?.value ?? t.value);
const why = (t) => one(typeof t.why === 'object' ? t.why?.why : t.why) || one(t.description);
// a short front matter in the shape design tools read: colours, type, spacing, corners
const pickFm = (pre, type) => sem.filter(([p, t]) => p.startsWith(pre) && (!type || t.type === type)).slice(0, 24);
const fm = ['---', `name: ${NAME}`, `packages: { tokens: ${tokensPkg}, components: ${reactPkg} }`, `themes: [${themes.join(', ')}]`];
for (const [label, pre, type] of [['colors', 'text.', 'color'], ['surfaces', 'surface.', 'color'], ['actions', 'action.', 'color'], ['status', 'status.', 'color'], ['spacing', 'gap.', null], ['corners', 'corner.', null], ['type', 'type.', null]]) {
  const rows = pickFm(pre, type); if (!rows.length) continue;
  fm.push(`${label}:`); for (const [p, t] of rows) fm.push(`  ${p.slice(pre.length).replace(/\./g, '-')}: ${JSON.stringify(themes.length > 1 && t.themes ? Object.fromEntries(themes.map((th) => [th, val(t, th)])) : t.value)}`);
}
fm.push('---');

// --- components: concept line and the default it must not become
const compDir = C.abs(C.componentsDir);
const comps = existsSync(compDir) ? readdirSync(compDir).filter((n) => existsSync(path.join(compDir, n, `${n}.why.json`))).sort() : [];
const compRows = comps.map((n) => {
  const w = JSON.parse(readFileSync(path.join(compDir, n, `${n}.why.json`), 'utf8'));
  const what = one(w.concept ?? w.identity_reason ?? (w.family ? `${w.family} family: ${w.family_difference}` : ''));
  const avoid = (w.default_to_avoid ?? []).map((a) => one(a.pattern)).filter(Boolean)[0] ?? '';
  return `| ${n} | ${cell(what.split(/(?<=\.)\s/)[0])} | ${cell(avoid)} |`;
});

// --- decisions: titles only, the record stays in system/DECISIONS.md
const decisions = [...read('system/DECISIONS.md').matchAll(/^### (D-\d+):? (.+)$/gm)].map(([, id, t]) => `- ${id} ${one(t)}`);

const md = [
  ...fm, '',
  `# ${NAME}`, '',
  intro, '',
  `Generated by kiln (\`tooling/kiln/design-md.mjs\`) from the tokens, the concept, every component's reasons and the decision log. Edit those, never this file.`, '',
  '## How to use this system', '',
  `Install \`${reactPkg}\` and \`${tokensPkg}\`, import \`${reactPkg}/all.css\` once, and build from the components below before writing new ones. Use semantic tokens (\`var(--ds-…)\`) and never a raw colour, size or duration. Other platforms read the same names: \`${tokensPkg}/tailwind\`, \`/swift\`, \`/kotlin\`, \`/dart\` and \`/figma\`.`, '',
  'This file cannot check your work, so keep to what kiln would have measured:', '',
  `- body text at ${C.contrast?.threshold ?? 4.5}:1 or more in every theme, over every backdrop the screen can show`,
  '- one loud element per surface, and no colour that carries meaning alone',
  '- every control reachable and visible by keyboard, with its focus ring',
  '- spacing, corners and motion only from the tokens, and nested corners that follow the outer one',
  '', '## Principles', '',
  ...principles.map((p) => `- **${p.id} ${p.title}.** ${p.line}`),
  '', '## Semantic tokens', '',
  `Values are given for ${themes.join(' and ')}. Component tokens point at these, and primitives sit under them; product code reads this tier.`, '',
  ...Object.entries(groups).flatMap(([g, rows]) => [`### ${g}`, '', `| token | ${themes.join(' | ')} | why |`, `|---|${themes.map(() => '---').join('|')}|---|`,
    ...rows.map(([p, t], i) => `| \`${t.css ?? p}\` | ${themes.map((th) => cell(val(t, th))).join(' | ')} | ${i && why(t) === why(rows[i - 1][1]) ? '〃' : cell(why(t))} |`), '']),
  '## Components', '',
  'What each one is, and the generic default it must not turn into.', '',
  '| component | what it is | never becomes |', '|---|---|---|', ...compRows, '',
  '## Locked decisions', '', ...decisions, '',
].join('\n');
writeFileSync(OUT, md);
// the book serves it too (/DESIGN.md next to llms.txt), so a tool can be pointed at a URL
const pub = path.join(C.abs(C.app), 'public');
if (!arg('--out') && existsSync(pub)) writeFileSync(path.join(pub, 'DESIGN.md'), md);
console.log(`✓ ${path.relative(ROOT, OUT)}: ${principles.length} principles, ${sem.length} semantic tokens, ${comps.length} components, ${decisions.length} decisions (${Math.round(md.length / 1024)} kB)`);
